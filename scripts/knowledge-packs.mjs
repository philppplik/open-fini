// Generates app/src/ai/packs/generated.js (data for the lazy OpenFini knowledge skills) from the sources of truth,
// so the assistant's answers about formats and shortcuts cannot drift from the code:
//   - platform/file-types.js (types registered with the OS), platform/format-verdicts.js (what each format can do),
//     the Office app registry (office/index.js: formats each Office app reads and writes)
//   - the command registry (default keyboard shortcuts, collected like scripts/wiki-shortcuts.mjs)
//
//   npm run knowledge:packs            rewrite the file
//   npm run knowledge:check            exit 1 when the committed file is out of date (also run by the tests)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(root, "app/src/ai/packs/generated.js");
const imp = (p) => import(pathToFileURL(join(root, p)).href);

export async function formatsMarkdown() {
  const { FILE_TYPES } = await imp("app/src/platform/file-types.js");
  const { FORMAT_VERDICTS } = await imp("app/src/platform/format-verdicts.js");
  const { officeApps } = await imp("app/src/office/index.js");
  const lines = ["## Formats by verdict (read / write / route)", "| Format | Extensions | Status | Read | Write |", "| --- | --- | --- | --- | --- |"];
  for (const v of FORMAT_VERDICTS) lines.push(`| ${v.name} | ${v.extensions.join(", ")} | ${v.status} | ${v.read} | ${v.write} |`);
  lines.push("", "## Office apps (opens / writes)");
  for (const a of officeApps()) {
    const r = a.formats.filter((f) => f.read).flatMap((f) => f.ext || []);
    const w = a.formats.filter((f) => f.write).map((f) => f.id);
    lines.push(`- ${a.kind}: opens ${r.map((e) => "." + e).join(" ")}; writes ${w.join(", ")}`);
  }
  lines.push("", "## Registered with the operating system (Open with OpenFini)");
  for (const k of ["document", "extension", "image", "import", "office", "code", "foreign"]) {
    const t = FILE_TYPES.filter((x) => x.kind === k);
    if (t.length) lines.push(`- ${k}: ${t.map((x) => x.ext.map((e) => "." + e).join("/")).join(", ")}`);
  }
  return lines.join("\n");
}

export async function shortcutsMarkdown() {
  const { collectCommands } = await imp("scripts/wiki-shortcuts.mjs");
  const cmds = (await collectCommands()).filter((c) => c.shortcut).sort((a, b) => a.id.localeCompare(b.id));
  const groups = new Map();
  for (const c of cmds) {
    const g = c.id.split(".")[0];
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(`${c.label}: ${c.shortcut}${c.altShortcut ? ` or ${c.altShortcut}` : ""}`);
  }
  return ["Mod = Ctrl on Windows and Linux, Cmd on macOS. Users can rebind every shortcut in Settings > Keyboard shortcuts.", ...[...groups].map(([g, l]) => `- ${g}: ${l.join("; ")}`)].join("\n");
}

export async function render() {
  const esc = (s) => JSON.stringify(s);
  return `// GENERATED by scripts/knowledge-packs.mjs - do not edit. Run npm run knowledge:packs after changing file types,
// format verdicts, Office formats or default shortcuts (npm test fails when this file is out of date).
export const FORMATS_MD = ${esc(await formatsMarkdown())};
export const SHORTCUTS_MD = ${esc(await shortcutsMarkdown())};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await render();
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (cur !== text) {
      console.error("app/src/ai/packs/generated.js is out of date. Run: npm run knowledge:packs");
      process.exit(1);
    }
    console.log("knowledge packs: up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
