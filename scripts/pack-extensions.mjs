// Packs the bundled extensions (extensions/<folder>/) into .ofext files and writes extensions/catalog.json.
//
//   npm run ext:pack-all                        build extensions/packages/*.ofext and extensions/catalog.json
//   node scripts/pack-extensions.mjs --check    fail when the committed packages/catalog are out of date (tests/CI)
//
// Source layout of an extension folder (see docs/bundled-extensions.md):
//   openfini-extension.json   manifest (validated here with app/src/extensions/manifest.js)
//   src/lib*.js               pure logic, importable by Node tests. `export` keywords are stripped and the files are
//                             concatenated (sorted by name) in front of main.js / panel.js when packed. They may import
//                             only from ../../_shared/*.js; those files are inlined first.
//   src/main.js               background script (commands) -> main.js in the package
//   src/panel.js              optional panel script -> panel/panel.js in the package
//   panel/, icon.svg, README.md, ...   copied as they are
// The extension runtime loads exactly one `main` file and inlines panel scripts, so shared code is bundled by
// concatenation (no module loader exists inside the sandbox). Output is deterministic.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { readFolder, zipFiles } from "../sdk/pack.mjs";
import { checkPackageFiles, validateManifest } from "../app/src/extensions/manifest.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const EXT_DIR = join(root, "extensions");
const enc = new TextEncoder();
const dec = new TextDecoder();

const IMPORT_RE = /^[ \t]*import\s[^;]*?from\s+["']([^"']+)["'];?[ \t]*$/gm;
const SHARED_RE = /^\.\.\/\.\.\/_shared\/([\w-]+\.js)$/;
const SIBLING_RE = /^\.\/lib[\w-]*\.js$/; // another src/lib*.js file: it is concatenated too, so the import is dropped

/** Removes `export` and shared imports so a lib file can be inlined into a plain script. */
export function stripExports(code) {
  for (const m of code.matchAll(IMPORT_RE)) {
    if (!SHARED_RE.test(m[1]) && !SIBLING_RE.test(m[1])) throw new Error(`lib files may only import from ../../_shared/ or ./lib*.js (got ${m[1]}): the sandbox has no module loader.`);
  }
  return code
    .replace(IMPORT_RE, "")
    .replace(/^export\s+(async\s+function|function|const|let|class)\b/gm, "$1")
    .replace(/^export\s*\{[^}]*\};?[ \t]*$/gm, "");
}

/** Names of the _shared files a source text imports. */
export const sharedImports = (code) => [...code.matchAll(IMPORT_RE)].map((m) => SHARED_RE.exec(m[1])?.[1]).filter(Boolean);

/** Builds the package file map of one extension folder. */
export function stage(dir) {
  const all = readFolder(dir);
  const files = {};
  for (const [path, bytes] of Object.entries(all)) {
    if (path.startsWith("src/") || path.startsWith("tests/") || path === "build-manifest.mjs") continue;
    // Line endings must not change the package (Windows checkouts may use CRLF): normalize text files to LF.
    files[path] = /\.(js|json|html|css|md|svg|txt)$/i.test(path) ? enc.encode(dec.decode(bytes).replace(/\r\n/g, "\n")) : bytes;
  }
  const read = (p) => (all[p] ? dec.decode(all[p]) : null);
  const libFiles = Object.keys(all).filter((p) => /^src\/lib[^/]*\.js$/.test(p)).sort();
  const shared = [...new Set(libFiles.flatMap((p) => sharedImports(read(p))))].sort();
  const sharedCode = shared.map((f) => stripExports(readFileSync(join(EXT_DIR, "_shared", f), "utf8")));
  const lib = libFiles.length ? [...sharedCode, ...libFiles.map((p) => stripExports(read(p)))].join("\n") : null;
  const header = "// Generated by scripts/pack-extensions.mjs from src/. Edit the files in src/, not this one.\n";
  const manifest = JSON.parse(read("openfini-extension.json"));
  const bundle = (file) => enc.encode(`${header}${lib ? `${lib}\n` : ""}${read(file)}`);
  if (read("src/main.js") != null) files[manifest.main || "main.js"] = bundle("src/main.js");
  if (read("src/panel.js") != null) files["panel/panel.js"] = bundle("src/panel.js");
  const ordered = { "openfini-extension.json": files["openfini-extension.json"] };
  for (const k of Object.keys(files).sort()) ordered[k] = files[k];
  return { files: ordered, manifest };
}

/** Studios an extension is useful in, from its commands and panels (all four when it does not restrict). */
export function studiosOf(manifest) {
  const c = manifest.contributes || {};
  const set = new Set();
  let unrestricted = false;
  for (const x of [...(c.commands || []), ...(c.panels || [])]) {
    if (x.studios?.length) x.studios.forEach((s) => set.add(s));
    else unrestricted = true;
  }
  if (unrestricted || !set.size) return ["vector", "pixel", "layout", "code"];
  return ["vector", "pixel", "layout", "code"].filter((s) => set.has(s));
}

/** Packs everything; returns { packages: {file: bytes}, catalog }. Throws on an invalid manifest. */
export async function packAll({ hostVersion } = {}) {
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const dirs = readdirSync(EXT_DIR, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith("_") && existsSync(join(EXT_DIR, d.name, "openfini-extension.json"))).map((d) => d.name).sort();
  const packages = {};
  const entries = [];
  for (const name of dirs) {
    const { files, manifest: raw } = stage(join(EXT_DIR, name));
    const res = validateManifest(raw, { hostVersion: hostVersion || pkg.version });
    const missing = res.ok ? checkPackageFiles(res.manifest, Object.keys(files)) : [];
    const errors = [...res.errors.map((e) => e.message), ...missing];
    if (errors.length) throw new Error(`extensions/${name}: ${errors.join("; ")}`);
    const bytes = await zipFiles(files);
    const file = `packages/${raw.id}-${raw.version}.ofext`;
    packages[file] = bytes;
    entries.push({
      id: raw.id,
      name: raw.name,
      description: raw.description,
      version: raw.version,
      engines: raw.engines.openfini,
      permissions: raw.permissions || [],
      studios: studiosOf(raw),
      icon: [raw.icon, raw.contributes?.commands?.[0]?.icon].find((i) => i && /^[a-z0-9-]+$/.test(i)) || "puzzle", // a Bootstrap Icons name for the gallery
      file,
      size: bytes.length,
    });
  }
  return { packages, catalog: { version: 1, extensions: entries } };
}

export const catalogText = (catalog) => `${JSON.stringify(catalog, null, 2)}\n`;

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const check = process.argv.includes("--check");
  try {
    const { packages, catalog } = await packAll();
    const stale = [];
    const out = join(EXT_DIR, "packages");
    mkdirSync(out, { recursive: true });
    if (!check) for (const f of readdirSync(out)) if (f.endsWith(".ofext") && !(`packages/${f}` in packages)) rmSync(join(out, f));
    for (const [file, bytes] of Object.entries(packages)) {
      const target = join(EXT_DIR, file);
      if (check) {
        if (!existsSync(target) || Buffer.compare(Buffer.from(bytes), readFileSync(target)) !== 0) stale.push(file);
      } else writeFileSync(target, bytes);
    }
    const cat = join(EXT_DIR, "catalog.json");
    if (check) {
      if (!existsSync(cat) || readFileSync(cat, "utf8") !== catalogText(catalog)) stale.push("catalog.json");
      if (stale.length) {
        console.error(`pack-extensions: out of date: ${stale.join(", ")}. Run: npm run ext:pack-all`);
        process.exit(1);
      }
      console.log("pack-extensions: packages and catalog are up to date");
    } else {
      writeFileSync(cat, catalogText(catalog));
      for (const e of catalog.extensions) console.log(`packed ${e.id}@${e.version} (${e.size} bytes)`);
    }
  } catch (err) {
    console.error(`pack-extensions: ${err.message}`);
    process.exit(1);
  }
}
