// A tiny static site generator for Markdown content: `content/**/*.md` + `layouts/*.html` → HTML pages. Pure: no DOM.
//
// Conventions
//   content/index.md           → index.html          (layout "index" unless front matter says otherwise)
//   content/posts/hello.md     → posts/hello.html    (layout "post" for pages in posts/, else "page")
//   content/guide/index.md     → guide/index.html
//   layouts/<name>.tmpl        → templates (.tmpl keeps them out of the page list) with {{title}}, {{{content}}}, {{#each posts}}…{{/each}}, {{#if date}}…{{/if}}
//   site.json                  → { "title": "...", "description": "...", "build": "markdown" }
// Front matter keys: title, description, date, layout, order, draft, slug. Links to other .md files become .html links,
// and paths that start with "/" are relative to the site root (so pages in sub folders still find /assets/…).
import { renderMarkdown, slugify } from "./markdown.js";
import { normalizePath, dirname } from "./paths.js";

/**
 * @typedef {{
 *   source: string, output: string, url: string, title: string, description: string, date: string, order: number,
 *   layout: string, meta: Record<string, any>, html: string, headings: { level: number, text: string, id: string }[], draft: boolean
 * }} SitePage
 * @typedef {{ files: Record<string, string>, pages: SitePage[], diagnostics: { severity: 'error'|'warning'|'info', message: string, file: string }[], skipped: string[] }} SiteBuild
 */

export const GENERATED_MARKER = "generated by OpenFini from";

const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const DEFAULT_LAYOUT = `<!doctype html>
<html lang="en-US">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{{title}}</title>
</head>
<body>
  <main>
{{{content}}}
  </main>
</body>
</html>
`;

/** Is `path` an input of the generator (a content file, a layout or the site configuration)? */
export function isSiteSource(path, options = {}) {
  const c = options.contentDir || "content";
  const l = options.layoutDir || "layouts";
  const p = normalizePath(path);
  return p === "site.json" || (p.startsWith(`${c}/`) && /\.(md|markdown)$/i.test(p)) || (p.startsWith(`${l}/`) && /\.(tmpl|html?)$/i.test(p));
}

/** Does the project use the Markdown site generator? (a content folder with Markdown files and a layouts folder) */
export function usesMarkdownSite(files, options = {}) {
  const c = options.contentDir || "content";
  const l = options.layoutDir || "layouts";
  const list = files.list();
  return list.some((p) => p.startsWith(`${c}/`) && /\.(md|markdown)$/i.test(p)) && list.some((p) => p.startsWith(`${l}/`));
}

/** Output path of a content file. */
export function outputPathFor(source, meta = {}, contentDir = "content") {
  let rel = normalizePath(source).slice(contentDir.length + 1).replace(/\.(md|markdown)$/i, "");
  if (typeof meta.slug === "string" && meta.slug.trim()) {
    const dir = dirname(rel);
    rel = `${dir ? `${dir}/` : ""}${slugify(meta.slug)}`;
  }
  return `${rel}.html`;
}

function relativeRoot(output) {
  const depth = output.split("/").length - 1;
  return depth ? "../".repeat(depth) : "";
}

const get = (obj, path) => path.split(".").reduce((o, k) => (o == null ? o : o[k]), obj);

/**
 * Renders a layout: `{{x}}` (escaped), `{{{x}}}` (raw), `{{#if x}}…{{/if}}`, `{{#each list}}…{{/each}}` (inside, `{{x}}`
 * reads the item, `{{@root.x}}`/`{{../x}}` the page). Unknown names render empty.
 * @param {string} tpl
 * @param {Record<string, any>} data
 * @returns {string}
 */
export function renderLayout(tpl, data) {
  const section = (text, scope, parent, depth) => {
    if (depth > 8) return "";
    let out = "";
    let i = 0;
    const re = /\{\{\{\s*([^}]+?)\s*\}\}\}|\{\{\s*(#if|#each|\/if|\/each)\s*([^}]*?)\s*\}\}|\{\{\s*([^}#/][^}]*?)\s*\}\}/g;
    const lookup = (name) => {
      if (name.startsWith("../")) return get(parent ?? {}, name.slice(3));
      if (name.startsWith("@root.")) return get(data, name.slice(6));
      if (name === "this") return scope;
      const v = get(scope, name);
      return v === undefined && scope !== data ? get(data, name) : v;
    };
    let m;
    while ((m = re.exec(text))) {
      out += text.slice(i, m.index);
      i = m.index + m[0].length;
      if (m[1] !== undefined) out += String(lookup(m[1]) ?? "");
      else if (m[4] !== undefined) out += esc(lookup(m[4]) ?? "");
      else if (m[2] === "#if" || m[2] === "#each") {
        const kind = m[2].slice(1);
        // find the matching close
        let d = 1;
        const inner = new RegExp(`\\{\\{\\s*(#${kind}|/${kind})\\b[^}]*\\}\\}`, "g");
        inner.lastIndex = i;
        let c;
        let end = -1;
        let closeEnd = -1;
        while ((c = inner.exec(text))) {
          if (c[1] === `#${kind}`) d++;
          else if (--d === 0) {
            end = c.index;
            closeEnd = c.index + c[0].length;
            break;
          }
        }
        if (end < 0) break;
        const body = text.slice(i, end);
        const v = lookup(m[3]);
        if (kind === "if") {
          if (v && !(Array.isArray(v) && !v.length)) out += section(body, scope, parent, depth + 1);
        } else if (Array.isArray(v)) {
          for (const item of v) out += section(body, typeof item === "object" && item ? item : { this: item }, scope, depth + 1);
        }
        i = closeEnd;
        re.lastIndex = i;
      }
    }
    return out + text.slice(i);
  };
  return section(tpl, data, null, 0);
}

function linkRewriter(output) {
  const root = relativeRoot(output);
  return (url, kind) => {
    if (/^([a-zA-Z][a-zA-Z0-9+.-]*:|\/\/|#)/.test(url)) return url;
    let u = url;
    if (u.startsWith("/")) u = root + u.slice(1);
    if (kind === "link") u = u.replace(/\.(md|markdown)(?=$|[?#])/i, ".html");
    return u;
  };
}

/**
 * Builds the HTML pages of a Markdown site.
 * @param {{ list(): string[], readText(path: string): string | null }} files
 * @param {{ contentDir?: string, layoutDir?: string, siteTitle?: string }} [options]
 * @returns {SiteBuild}
 */
export function buildMarkdownSite(files, options = {}) {
  const contentDir = options.contentDir || "content";
  const layoutDir = options.layoutDir || "layouts";
  /** @type {SiteBuild} */
  const result = { files: {}, pages: [], diagnostics: [], skipped: [] };
  const warn = (message, file, severity = "warning") => result.diagnostics.push({ severity, message, file });
  let site = { title: options.siteTitle || "My site", description: "" };
  const cfg = files.readText("site.json");
  if (cfg != null) {
    try {
      site = { ...site, ...JSON.parse(cfg) };
    } catch {
      warn("site.json is not valid JSON; defaults were used.", "site.json");
    }
  }
  const layouts = {};
  for (const p of files.list()) if (p.startsWith(`${layoutDir}/`) && /\.(tmpl|html?)$/i.test(p)) layouts[p.slice(layoutDir.length + 1).replace(/\.(tmpl|html?)$/i, "")] = files.readText(p);

  // pass 1: render every page
  for (const source of files.list().sort()) {
    if (!source.startsWith(`${contentDir}/`) || !/\.(md|markdown)$/i.test(source)) continue;
    if (source.split("/").some((s) => s.startsWith("_"))) continue;
    const text = files.readText(source);
    if (text == null) continue;
    const first = renderMarkdown(text, { idPrefix: "" });
    const meta = first.meta;
    const output = outputPathFor(source, meta, contentDir);
    const rendered = renderMarkdown(text, { idPrefix: "", resolveUrl: linkRewriter(output) });
    const stem = output.replace(/\.html$/, "").split("/").pop();
    const dir = dirname(output);
    const isIndex = output === "index.html";
    const layout = typeof meta.layout === "string" && meta.layout ? meta.layout : isIndex ? "index" : dir.split("/")[0] === "posts" ? "post" : "page";
    const date = meta.date instanceof Date ? meta.date.toISOString().slice(0, 10) : meta.date != null ? String(meta.date) : "";
    const title = String(meta.title || rendered.title || stem.replace(/[-_]+/g, " ").replace(/^\w/, (c) => c.toUpperCase()));
    result.pages.push({
      source, output, url: output, title, description: String(meta.description || ""), date, order: Number.isFinite(Number(meta.order)) ? Number(meta.order) : 1000,
      layout, meta, html: rendered.html, headings: rendered.headings, draft: meta.draft === true,
    });
  }
  const live = result.pages.filter((p) => !p.draft);
  const dated = live.filter((p) => p.date && p.output !== "index.html").sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.title.localeCompare(b.title)));

  // pass 2: layouts
  for (const page of live) {
    const root = relativeRoot(page.output);
    const rel = (url) => root + url;
    // the navigation lists pages, not posts: dated pages appear only on the home page unless they set `nav:`
    const navPages = live.filter((p) => !p.meta.hidden && (!p.date || p.output === "index.html" || p.meta.nav)).sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));
    const nav = navPages.map((p) => ({ title: String(p.meta.nav && p.meta.nav !== true ? p.meta.nav : p.title), url: rel(p.url), current: p === page, aria: p === page ? ' aria-current="page"' : "" }));
    const data = {
      title: page.title,
      fullTitle: page.title === site.title ? page.title : `${page.title} · ${site.title}`,
      description: page.description,
      date: page.date,
      content: page.html,
      root,
      url: page.output,
      site,
      meta: page.meta,
      nav,
      posts: dated.map((p) => ({ title: p.title, description: p.description, date: p.date, url: rel(p.url), excerpt: excerptOf(p.html) })),
      toc: page.headings.filter((h) => h.level >= 2 && h.level <= 3).map((h) => ({ text: h.text, id: h.id, level: h.level })),
      hasToc: page.headings.filter((h) => h.level >= 2 && h.level <= 3).length > 1,
    };
    let tpl = layouts[page.layout];
    if (tpl == null) {
      tpl = layouts.page ?? layouts.post ?? layouts.index;
      if (tpl == null) {
        tpl = DEFAULT_LAYOUT;
        warn(`No layout "${page.layout}" (or any layout) in ${layoutDir}/; a plain page was used.`, page.source);
      } else warn(`Layout "${page.layout}" does not exist in ${layoutDir}/; another layout was used.`, page.source);
    }
    let html = renderLayout(tpl, data);
    // the generated marker (second line) protects hand-written files from being overwritten
    const marker = `<!-- ${GENERATED_MARKER} ${page.source} -->`;
    html = /^<!doctype[^>]*>/i.test(html.trimStart()) ? html.replace(/^(\s*<!doctype[^>]*>)/i, `$1\n${marker}`) : `${marker}\n${html}`;
    result.files[page.output] = html.endsWith("\n") ? html : `${html}\n`;
  }
  if (!result.pages.length) warn(`There are no Markdown files in ${contentDir}/.`, contentDir, "info");
  return result;
}

function excerptOf(html) {
  const m = /<p>([\s\S]*?)<\/p>/.exec(html);
  return m ? m[1].replace(/<[^>]+>/g, "").trim().slice(0, 220) : "";
}

/**
 * Which generated files may be written: new files, and files that carry the generator marker. Others are reported
 * so hand-written pages are never overwritten.
 * @param {SiteBuild} build
 * @param {{ readText(path: string): string | null }} existing
 * @returns {{ write: Record<string, string>, skipped: string[] }}
 */
export function planWrites(build, existing) {
  const write = {};
  const skipped = [];
  for (const [path, html] of Object.entries(build.files)) {
    const cur = existing.readText(path);
    if (cur == null || cur.includes(GENERATED_MARKER)) {
      if (cur !== html) write[path] = html;
    } else skipped.push(path);
  }
  return { write, skipped };
}
